#!/usr/bin/env python3
"""Build playlist/master.m3u from public, non-VAVOO M3U sources.

The generated playlist is a catalogue index only: it contains direct HTTP(S)
stream URLs from public playlists and never resolves, rewrites, or publishes
VAVOO URLs. Add/remove sources in SOURCES below. The workflow runs this file
every six hours and preserves the last good master if any required source fails.
"""
from __future__ import annotations

import os
import re
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

import requests

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "playlist" / "master.m3u"
MAX_SOURCE_BYTES = 32 * 1024 * 1024
TIMEOUT = (10, 45)
RETRIES = 3
USER_AGENT = "KENZINISS-M3U-Builder/1.0 (+https://github.com/Nissay8z/KENZINISS)"


@dataclass(frozen=True)
class Source:
    source_id: str
    name: str
    url: str
    minimum_channels: int = 8


# Public/community-maintained M3U sources. No VAVOO feed belongs here.
SOURCES = (
    Source(
        "iptv-org-fr",
        "IPTV-org France",
        "https://iptv-org.github.io/iptv/countries/fr.m3u",
        15,
    ),
    Source(
        "iptv-org-arab",
        "IPTV-org Monde arabe",
        "https://iptv-org.github.io/iptv/regions/arab.m3u",
        25,
    ),
    Source(
        "iptv-org-africa",
        "IPTV-org Afrique",
        "https://iptv-org.github.io/iptv/regions/afr.m3u",
        25,
    ),
    Source(
        "pluto-tv-fr",
        "Pluto TV France",
        "https://i.mjh.nz/PlutoTV/fr.m3u8",
        8,
    ),
    Source(
        "samsung-tv-fr",
        "Samsung TV Plus France",
        "https://i.mjh.nz/SamsungTVPlus/fr.m3u8",
        8,
    ),
    Source(
        "free-tv-world",
        "Free-TV International",
        "https://raw.githubusercontent.com/Free-TV/IPTV/master/playlist.m3u8",
        8,
    ),
)

ATTRIBUTE_RE = re.compile(r'\s+x-source-(?:id|name)="[^"]*"', re.IGNORECASE)


def is_http_stream(value: str) -> bool:
    value = value.strip()
    return value.startswith("https://") or value.startswith("http://")


def add_source_metadata(extinf: str, source: Source) -> str:
    """Attach stable source IDs without changing stream URLs or channel title."""
    head, separator, title = extinf.partition(",")
    # Avoid duplicate markers if a source was already generated by this script.
    head = ATTRIBUTE_RE.sub("", head)
    head = (
        f'{head} x-source-id="{source.source_id}"'
        f' x-source-name="{source.name}"'
    )
    return head + (separator + title if separator else "")


def parse_entries(text: str, source: Source) -> list[str]:
    """Return normalized EXTINF/URL pairs; ignore comments and non-HTTP schemes."""
    result: list[str] = []
    pending_extinf: str | None = None
    seen_urls: set[str] = set()

    for raw_line in text.lstrip("\ufeff").splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line.startswith("#EXTINF:"):
            pending_extinf = line
            continue
        if line.startswith("#"):
            # Preserve the pending entry across optional #EXTVLCOPT/#EXTGRP lines.
            continue
        if pending_extinf is None:
            continue

        # The public master must not contain VAVOO references or local proxy URLs.
        if not is_http_stream(line) or "vavoo" in line.lower():
            pending_extinf = None
            continue
        if line in seen_urls:
            pending_extinf = None
            continue

        seen_urls.add(line)
        result.append(add_source_metadata(pending_extinf, source))
        result.append(line)
        pending_extinf = None

    return result


def download_source(source: Source) -> list[str]:
    last_error: Exception | None = None
    headers = {
        "User-Agent": USER_AGENT,
        "Accept": "application/vnd.apple.mpegurl, audio/x-mpegurl, text/plain, */*",
        "Cache-Control": "no-cache",
    }

    for attempt in range(1, RETRIES + 1):
        try:
            response = requests.get(source.url, headers=headers, timeout=TIMEOUT)
            response.raise_for_status()
            if len(response.content) > MAX_SOURCE_BYTES:
                raise ValueError(f"source exceeds {MAX_SOURCE_BYTES // (1024 * 1024)} MiB")
            text = response.content.decode("utf-8-sig", errors="replace")
            if "#EXTM3U" not in text[:2048]:
                raise ValueError("response is not an extended M3U playlist")

            entries = parse_entries(text, source)
            count = len(entries) // 2
            if count < source.minimum_channels:
                raise ValueError(
                    f"only {count} usable channels (minimum {source.minimum_channels})"
                )
            print(f"OK {source.name}: {count} channels")
            return entries
        except Exception as error:  # keep the last good master if any input goes bad
            last_error = error
            print(
                f"WARNING {source.name}: attempt {attempt}/{RETRIES} failed: {error}",
                file=sys.stderr,
            )

    raise RuntimeError(
        f"Cannot refresh master because source '{source.name}' failed: {last_error}"
    )


def write_atomically(lines: Iterable[str]) -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(
        prefix="master-", suffix=".m3u.tmp", dir=str(OUTPUT.parent)
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write("#EXTM3U\n")
            for line in lines:
                stream.write(line.rstrip("\r\n") + "\n")
        os.replace(temporary, OUTPUT)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def generate_master() -> int:
    master: list[str] = []
    total = 0
    per_source: dict[str, int] = {}

    for source in SOURCES:
        entries = download_source(source)
        count = len(entries) // 2
        per_source[source.source_id] = count
        master.extend(entries)
        total += count

    if total < 50:
        raise RuntimeError(f"Refusing to publish suspiciously small master ({total} channels)")

    write_atomically(master)
    size = OUTPUT.stat().st_size
    print(f"Generated {OUTPUT.relative_to(ROOT)}: {total} channels, {size:,} bytes")
    print("Sources: " + ", ".join(f"{key}={value}" for key, value in per_source.items()))
    print("VAVOO: excluded (the Android app resolves VAVOO natively on channel selection).")
    return total


if __name__ == "__main__":
    try:
        generate_master()
    except Exception as error:
        print(f"ERROR: {error}", file=sys.stderr)
        # Do not replace playlist/master.m3u if a required source is down.
        sys.exit(1)
